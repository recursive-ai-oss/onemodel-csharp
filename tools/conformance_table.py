"""Write docs/conformance.md from the runner's result files.

    conformance_table.py <results-dir> [--out docs/conformance.md] [--data <backend-test-root>]

<results-dir> holds conformance-fast.tsv and conformance-exact.tsv, written by
`OnnxSweep conformance` (tools/conformance.sh runs both steps). Columns of the TSV files, tab separated, one case per line:
group, case, opset, ops, mode, status, reason. Status is one of pass, fail, unsupported-op, unsupported-type, not-exact, known-diff.
"""
from __future__ import annotations

import argparse
import re
from collections import Counter, defaultdict
from pathlib import Path

STATUSES = ["pass", "fail", "unsupported-op", "unsupported-type", "not-exact", "known-diff"]


def read(path: Path) -> list[dict]:
    rows = []
    for line in path.read_text(encoding="utf-8").splitlines():
        f = line.split("\t")
        if len(f) < 7:
            f += [""] * (7 - len(f))
        rows.append(dict(group=f[0], case=f[1], opset=int(f[2] or 0), ops=[o for o in f[3].split(",") if o],
                         mode=f[4], status=f[5], reason=f[6]))
    return rows


def snake(op: str) -> str:
    return re.sub(r"(?<=[a-z0-9])(?=[A-Z])|(?<=[A-Z])(?=[A-Z][a-z])", "_", op.split(".")[-1]).lower()


def attribute(rows: list[dict]) -> None:
    """Give every node case an operator: its only operator, else the longest operator name its case name starts with."""
    known = {o for r in rows if r["group"] == "node" for o in r["ops"]}
    names = sorted(((snake(o), o) for o in known), key=lambda t: len(t[0]), reverse=True)
    plain = {r["case"]: r for r in rows if r["group"] == "node" and not r["case"].endswith("_expanded") and len(r["ops"]) == 1}
    for r in rows:
        r["op"] = None
        if r["group"] != "node":
            continue
        if len(r["ops"]) == 1:
            r["op"] = r["ops"][0]
            continue
        # an expanded case (the operator written out as its function body) belongs to the operator of its unexpanded twin
        twin = plain.get(re.sub(r"_expanded(_ver\d+)?$", "", r["case"]))
        if twin is not None:
            r["op"] = twin["ops"][0]
            continue
        name = r["case"].removeprefix("test_")
        for sn, op in names:
            if name == sn or name.startswith(sn + "_") or re.match(re.escape(sn) + r"\d", name) or name == sn.replace("_", "") or name.startswith(sn.replace("_", "") + "_"):
                r["op"] = op
                break
        if r["op"] is None:
            r["op"] = "(other)"


def short(reason: str) -> str:
    m = re.match(r"The model uses operators this library does not implement: (.*)", reason)
    if m:
        return "no kernel: " + re.sub(r"\.$", "", m.group(1))
    reason = re.sub(r"output \d+ \(.*?\): element \d+: got .*", "wrong values", reason)
    return reason[:110]


def cause_text(rows: list[dict]) -> str:
    c = Counter(short(r["reason"]) for r in rows)
    return "; ".join(f"{k}" + (f" ×{n}" if n > 1 else "") for k, n in sorted(c.items(), key=lambda kv: (-kv[1], kv[0]))[:3]) + (
        f"; +{len(c) - 3} more" if len(c) > 3 else "")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("results")
    ap.add_argument("--out", default="docs/conformance.md")
    ap.add_argument("--version", default="")
    a = ap.parse_args()
    d = Path(a.results)
    fast = read(d / "conformance-fast.tsv")
    exact = read(d / "conformance-exact.tsv") if (d / "conformance-exact.tsv").exists() else []
    attribute(fast)
    attribute(exact)
    exact_by_case = {(r["group"], r["case"]): r for r in exact}

    total = Counter(r["status"] for r in fast)
    etotal = Counter(r["status"] for r in exact)
    n = len(fast)
    out: list[str] = []
    w = out.append
    w("# Conformance: onnx/backend/test")
    w("")
    w("Generated by `tools/conformance.sh` (it runs `OnnxSweep conformance` over the frozen ONNX 1.22.0 backend-test data, then "
      "`tools/conformance_table.py`). Nothing here is edited by hand. The method is at the end.")
    w("")
    w("## Summary")
    w("")
    w("| Mode | Cases | pass | fail | unsupported-op | unsupported-type | not-exact | known-diff |")
    w("|---|---:|---:|---:|---:|---:|---:|---:|")
    w(f"| fast | {n} | " + " | ".join(str(total[s]) for s in STATUSES) + " |")
    if exact:
        w(f"| exact | {len(exact)} | " + " | ".join(str(etotal[s]) for s in STATUSES) + " |")
    w("")
    w("A **gap** is an `unsupported-op` or `unsupported-type` case: the library says so, loudly, when the session is created or first run. "
      "A **fail** is a case that ran (or threw) and is wrong: a defect. A **known-diff** is a failing case whose difference is understood and listed in the runner with its reason (Resize align_corners follows ONNX Runtime; the DFT inverse cases' expected data is noisier than their tolerance). "
      "A **not-exact** case, in exact mode only, uses an operator that has no exact kernel yet; its result is not computed.")
    w("")
    w("| Group | Cases | pass | fail | gap | not-exact (exact mode) |")
    w("|---|---:|---:|---:|---:|---:|")
    for g in ["node", "simple", "pytorch-converted", "pytorch-operator"]:
        rs = [r for r in fast if r["group"] == g]
        if not rs:
            continue
        c = Counter(r["status"] for r in rs)
        ne = sum(1 for r in exact if r["group"] == g and r["status"] == "not-exact")
        w(f"| {g} | {len(rs)} | {c['pass']} | {c['fail']} | {c['unsupported-op'] + c['unsupported-type']} | {ne} |")
    w("")

    # ---- per operator (node cases)
    ops: dict[str, list[dict]] = defaultdict(list)
    for r in fast:
        if r["group"] == "node":
            ops[r["op"]].append(r)
    w("## Operators (node cases)")
    w("")
    w("`Opsets` lists the opset versions of the cases that pass. `exact` is the pass count of the same cases in exact mode; "
      "`not-exact` counts those that need an operator without an exact kernel. Gap causes are the most frequent reasons.")
    w("")
    w("| Operator | Opsets passing | Cases | pass | fail | gap | exact pass | not-exact | Gap and fail causes |")
    w("|---|---|---:|---:|---:|---:|---:|---:|---|")
    for op in sorted(ops, key=str.lower):
        rs = ops[op]
        c = Counter(r["status"] for r in rs)
        ps = sorted({r["opset"] for r in rs if r["status"] == "pass"})
        ex = [exact_by_case.get((r["group"], r["case"])) for r in rs]
        ep = sum(1 for e in ex if e and e["status"] == "pass")
        ne = sum(1 for e in ex if e and e["status"] == "not-exact")
        bad = [r for r in rs if r["status"] not in ("pass",)]
        gap = c["unsupported-op"] + c["unsupported-type"]
        w(f"| {op} | {', '.join(map(str, ps)) or '-'} | {len(rs)} | {c['pass']} | {c['fail']} | {gap} | {ep} | {ne} | {cause_text(bad) if bad else ''} |")
    w("")

    # ---- other groups
    w("## Model cases (simple, pytorch-converted, pytorch-operator)")
    w("")
    w("| Group | Case | Opset | Fast | Exact | Reason |")
    w("|---|---|---:|---|---|---|")
    for r in fast:
        if r["group"] == "node" or r["status"] == "pass" and exact_by_case.get((r["group"], r["case"]), {"status": "pass"})["status"] == "pass":
            continue
        e = exact_by_case.get((r["group"], r["case"]))
        w(f"| {r['group']} | {r['case']} | {r['opset']} | {r['status']} | {e['status'] if e else ''} | {short(r['reason'])} |")
    passing = sum(1 for r in fast if r["group"] != "node" and r["status"] == "pass"
                  and exact_by_case.get((r["group"], r["case"]), {"status": "pass"})["status"] == "pass")
    w("")
    w(f"{passing} further model cases pass in both modes and are not listed.")
    w("")

    # ---- missing operators
    missing: dict[str, int] = Counter()
    for r in fast:
        if r["status"] == "unsupported-op":
            m = re.match(r"The model uses operators this library does not implement: (.*)", r["reason"])
            if m:
                for part in re.split(r", (?=[A-Za-z_.]+ \(opset)", m.group(1).rstrip(".")):
                    missing[re.sub(r" \(opset \d+\)", "", part)] += 1
    w("## Operators with no kernel")
    w("")
    w("Operators named by `unsupported-op` cases, with the number of cases that need them (a case can need several).")
    w("")
    w("| Operator | Cases |")
    w("|---|---:|")
    for op, k in sorted(missing.items(), key=lambda kv: (-kv[1], kv[0])):
        w(f"| {op} | {k} |")
    w("")

    # ---- every non-pass case
    w("## Every case that does not pass")
    w("")
    w("One line per case: `case` (opset), fast status, exact status, reason.")
    w("")
    w("<details><summary>List</summary>")
    w("")
    w("| Case | Opset | Fast | Exact | Reason |")
    w("|---|---:|---|---|---|")
    for r in fast:
        e = exact_by_case.get((r["group"], r["case"]))
        if r["status"] == "pass" and (e is None or e["status"] == "pass"):
            continue
        reason = short(r["reason"] if r["status"] != "pass" else e["reason"])
        w(f"| {r['case']} | {r['opset']} | {r['status']} | {e['status'] if e else ''} | {reason} |")
    w("")
    w("</details>")
    w("")

    w("## Method")
    w("")
    w("- **Data.** The frozen ONNX 1.22.0 `onnx/backend/test/data` directories `node`, `simple`, `pytorch-converted` and "
      "`pytorch-operator`, fetched by `tools/fetch_backend_test.py` at a pinned SHA-256 (the data is never committed). ONNX 1.23 and later no "
      "longer ship frozen node cases, so cases for operators newer than that release are not in the data; see the gaps above.")
    w("- **Run.** Each case's `model.onnx` is imported and a `Session` is created in the mode under test (`Fast` or `Exact`, one "
      "intra-op thread, default optimization level). Every `test_data_set_*` is fed in and every output compared with the recorded "
      "output.")
    w("- **Tolerance.** Floating-point outputs (float16, bfloat16, float32, float64) pass when each element satisfies "
      "`|got - want| <= 1e-7 + 1e-3 * |want|` or both are NaN or equal (this includes infinities); integer and boolean outputs "
      "must be equal; shapes and element types must be equal.")
    w("- **Status.** `unsupported-op`: no kernel for the operator at that opset, or the operator rejects an attribute value or rank it "
      "does not handle. `unsupported-type`: an element type or value kind the library does not have (string, 4-bit, 8-bit float, "
      "sequence, optional, map). `not-exact`: exact mode only, an operator without an exact kernel. `fail`: anything else that is not a pass.")
    w("- **Attribution.** A node case counts under its only operator; a case with several operators (the `_expanded` "
      "function bodies) counts under the longest operator name its case name starts with.")
    w("")
    Path(a.out).write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {a.out}: {n} cases, fast pass {total['pass']}, fail {total['fail']}")


if __name__ == "__main__":
    main()
